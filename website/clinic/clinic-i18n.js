  const COPY = {
    en: EN,
    he: HE,
    es: ES,
    fr: FR,
    de: DE,
    ar: AR,
    ru: RU,
    pt: PT,
    it: IT,
    tr: TR,
  };

  function normalize(code) {
    if (!code) return null;
    const base = String(code).toLowerCase().split('-')[0];
    return CLINIC_LOCALES.some((l) => l.code === base) ? base : null;
  }

  function detectLocale() {
    try {
      const saved = normalize(localStorage.getItem(STORE_KEY));
      if (saved) return saved;
    } catch {
      /* ignore */
    }
    const langs = Array.isArray(navigator.languages) ? navigator.languages : [navigator.language];
    for (const l of langs) {
      const hit = normalize(l);
      if (hit) return hit;
    }
    return 'en';
  }

  let current = detectLocale();

  function localeMeta(code) {
    return CLINIC_LOCALES.find((l) => l.code === (code || current)) || CLINIC_LOCALES[0];
  }

  function setLocale(code) {
    const next = normalize(code) || 'en';
    current = next;
    try {
      localStorage.setItem(STORE_KEY, next);
    } catch {
      /* ignore */
    }
    applyDocumentLocale();
    return next;
  }

  function applyDocumentLocale() {
    const meta = localeMeta(current);
    document.documentElement.lang = meta.code;
    document.documentElement.dir = meta.dir;
  }

  function interpolate(template, vars) {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (whole, key) =>
      Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : whole,
    );
  }

  function t(key, vars) {
    const table = COPY[current] || {};
    const value = table[key] != null ? table[key] : EN[key];
    if (value == null) return key;
    return interpolate(value, vars);
  }

  /**
   * Day counts with Slavic / Arabic plural forms.
   * he: 1 one, 2 two, else many · ru: 1 one, 2–4 few, else many · ar: 1/2/3–10/11+
   */
  function pluralDays(n) {
    const abs = Math.abs(Number(n) || 0);
    const vars = { n: abs };
    if (current === 'ru') {
      const mod10 = abs % 10;
      const mod100 = abs % 100;
      if (mod10 === 1 && mod100 !== 11) return t('daysOne', vars);
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return t('daysFew', vars);
      return t('daysMany', vars);
    }
    if (current === 'ar') {
      if (abs === 1) return t('daysOne', vars);
      if (abs === 2) return t('daysTwo', vars);
      if (abs >= 3 && abs <= 10) return t('daysFew', vars);
      return t('daysMany', vars);
    }
    if (current === 'he') {
      if (abs === 1) return t('daysOne', vars);
      if (abs === 2) return t('daysTwo', vars);
      return t('daysMany', vars);
    }
    return abs === 1 ? t('daysOne', vars) : t('daysMany', vars);
  }

  global.ClinicI18n = {
    CLINIC_LOCALES,
    COPY,
    t,
    pluralDays,
    setLocale,
    applyDocumentLocale,
    getLocale: () => current,
    localeMeta,
  };
